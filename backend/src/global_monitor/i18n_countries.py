def country_name(iso3: str, lang: str, fallback: str | None = None) -> str:
    """Localized name, falling back to the caller's English name (the
    database value) so an uncovered country still renders."""
    lang = norm_lang(lang)
    table = COUNTRY_NAME.get(iso3.upper(), {})
    if lang == DEFAULT_LANG and not table:
        return fallback or iso3
    return pick(table, lang, fallback or iso3)
